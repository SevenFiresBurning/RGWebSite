const assert = require('node:assert/strict'), fs = require('node:fs'), path = require('node:path');
const {DatabaseSync} = require('node:sqlite');
(async () => {
  const db = new DatabaseSync(':memory:');
  db.exec(fs.readFileSync(path.join(__dirname,'../migrations/0001_arcade_scores.sql'),'utf8'));
  db.exec(fs.readFileSync(path.join(__dirname,'../migrations/0002_arcade_wall.sql'),'utf8'));
  const binding = {prepare(sql) {const bind = (...values) => {const statement = db.prepare(sql);return {all:async()=>({results:statement.all(...values)}), first:async()=>statement.get(...values), run:async()=>({meta:{changes:statement.run(...values).changes}})};}; return {bind,all:()=>bind().all()};}};
  const source = fs.readFileSync(path.join(__dirname,'../functions/api/arcade/scores.js'),'utf8');
  const {onRequest} = await import('data:text/javascript;base64,'+Buffer.from(source).toString('base64'));
  const get = game => onRequest({request:new Request('https://example.test/api/arcade/scores?game='+game),env:{ARCADE_DB:binding}});
  const post = (value,ip='one',origin='https://example.test') => onRequest({request:new Request('https://example.test/api/arcade/scores',{method:'POST',headers:{Origin:origin,'Content-Type':'application/json','CF-Connecting-IP':ip},body:JSON.stringify(value)}),env:{ARCADE_DB:binding}});
  const score = n=>({id:crypto.randomUUID(),game:'hat-rack-rhythm',initials:'ABC',score:n});
  assert.equal((await onRequest({request:new Request('https://example.test'),env:{}})).status,503);
  assert.equal((await get('bad')).status,400);
  assert.equal((await post(score(100),'one','https://other.test')).status,403);
  assert.equal((await post({...score(100),initials:'AB'})).status,400);
  const first=score(100);
  assert.equal((await post(first)).status,200);
  assert.equal((await post(first)).status,200);
  assert.equal((await post({...first,score:101})).status,409);
  await post(score(300)); await post(score(200));
  assert.equal((await post(score(400))).status,429);
  assert.deepEqual((await (await get('hat-rack-rhythm')).json()).scores.map(x=>x.score),[300,200,100]);
  await post({...score(500),game:'ur-in-trouble'},'two');
  assert.deepEqual((await (await get('ur-in-trouble')).json()).scores.map(x=>x.score),[500]);
  for(let i=0;i<12;i++) await post(score(1000+i),'ip'+i);
  assert.equal((await (await get('hat-rack-rhythm')).json()).scores.length,10);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM arcade_scores').get().n,16);
  const wallSource = fs.readFileSync(path.join(__dirname,'../functions/api/arcade/wall.js'),'utf8');
  const wall = (await import('data:text/javascript;base64,'+Buffer.from(wallSource).toString('base64'))).onRequest;
  const wallGet = () => wall({request:new Request('https://example.test/api/arcade/wall'),env:{ARCADE_DB:binding}});
  const wallPost = (value,ip='wall-test') => wall({request:new Request('https://example.test/api/arcade/wall',{method:'POST',headers:{Origin:'https://example.test','Content-Type':'application/json','CF-Connecting-IP':ip},body:JSON.stringify(value)}),env:{ARCADE_DB:binding}});
  const note={id:crypto.randomUUID(),text:'<img src=x onerror=alert(1)>',color:'ink'};
  assert.equal((await wallPost({...note,text:' '})).status,400);
  assert.equal((await wallPost({...note,text:'x'.repeat(161)})).status,400);
  assert.equal((await wallPost({...note,color:'bad'})).status,400);
  assert.equal((await wallPost(note)).status,200);
  assert.equal((await wallPost(note)).status,200);
  assert.equal((await wallPost({...note,text:'Changed'})).status,409);
  assert.equal((await (await wallGet()).json()).notes[0].text,note.text);
  await wallPost({...note,id:crypto.randomUUID(),text:'Second'});
  await wallPost({...note,id:crypto.randomUUID(),text:'Third'});
  assert.equal((await wallPost({...note,id:crypto.randomUUID()})).status,429);
  for(let i=0;i<55;i++) await wallPost({...note,id:crypto.randomUUID(),text:'Note '+i},'wall-ip-'+i);
  assert.equal((await (await wallGet()).json()).notes.length,50);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM arcade_wall').get().n,58);
  db.close(); console.log('PASS: real SQLite schemas, public scores/wall reads, rankings, validation, retries, rate limits, plain-text messages, display limits and retained history.');
})().catch(error=>{console.error(error);process.exitCode=1;});
